// The controller wants the frame as two 1bpp planes: one holding the high bit
// of every pixel's level, one the low bit. Both take four pixels of a source
// byte down to a nibble, so two source bytes make one plane byte.
//
// Which plane takes which bit is the one thing Waveshare's own demos disagree
// about -- see the comment on pack_plane() in epd.c.
static inline uint8_t grayHighNibble(uint8_t src)
{
  return (uint8_t)(((src >> 4) & 8) | ((src >> 3) & 4) | ((src >> 2) & 2) | ((src >> 1) & 1));
}

static inline uint8_t grayLowNibble(uint8_t src)
{
  return (uint8_t)(((src >> 3) & 8) | ((src >> 2) & 4) | ((src >> 1) & 2) | (src & 1));
}
